private void cargarDatosTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tablaHuespedes.getModel();
        modelo.setRowCount(0);
        
        ArrayList<Huesped> lista = controlador.obtenerHuespedes();
        if (lista != null) {
            for (Huesped h : lista) {
                Object[] fila = {
                    h.getIdentificacion(),
                    h.getNombreCompleto(),
                    h.getTelefono(),
                    h.getCorreo()
                };
                modelo.addRow(fila);
            }
        }
    
}
